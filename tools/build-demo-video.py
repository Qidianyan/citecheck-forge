def assert_zero_blue_purple_pil(img: Image.Image, label: str, sat_thresh: float = 0.14, val_thresh: float = 0.14) -> dict:
    """Scan every pixel of an RGB image in vectorized NumPy HSV; forbid 175°..320° (cyan/teal/blue/purple)."""
    arr = np.asarray(img.convert("RGB"), dtype=np.float32) / 255.0
    r, g, b = arr[..., 0], arr[..., 1], arr[..., 2]
    mx = np.maximum(np.maximum(r, g), b)
    mn = np.minimum(np.minimum(r, g), b)
    diff = mx - mn

    s = np.where(mx > 1e-6, diff / np.maximum(mx, 1e-6), 0.0)
    v = mx

    h = np.zeros_like(mx)
    mask = diff > 1e-6
    r_max = mask & (mx == r)
    g_max = mask & (mx == g) & ~r_max
    b_max = mask & ~r_max & ~g_max

    h[r_max] = ((g[r_max] - b[r_max]) / diff[r_max]) % 6.0
    h[g_max] = ((b[g_max] - r[g_max]) / diff[g_max]) + 2.0
    h[b_max] = ((r[b_max] - g[b_max]) / diff[b_max]) + 4.0
    hue_deg = (h * 60.0) % 360.0

    forbidden = (hue_deg >= 175.0) & (hue_deg <= 320.0) & (s >= sat_thresh) & (v >= val_thresh)
    bad_count = int(np.count_nonzero(forbidden))
    in_band = (hue_deg >= 175.0) & (hue_deg <= 320.0) & (v >= val_thresh)
    max_sat_in_band = float(np.max(s[in_band])) if np.any(in_band) else 0.0
    if bad_count > 0:
        raise AssertionError(
            f"[COLOR VIOLATION] {label}: {bad_count} pixels in HSV 175°..320° (max S={max_sat_in_band:.3f})"
        )
    return {"label": label, "pixels": int(r.size), "forbidden_pixels": bad_count, "max_sat_175_320": round(max_sat_in_band, 4)}


def load_font(size: int, bold: bool = False, mono: bool = False) -> ImageFont.FreeTypeFont:
    candidates = []
    if mono:
        candidates = [
            "/System/Library/Fonts/Menlo.ttc",
            "/System/Library/Fonts/SFNSMono.ttf",
            "/Library/Fonts/Courier New.ttf",
        ]
    elif bold:
        candidates = [
            "/System/Library/Fonts/Supplemental/Georgia Bold.ttf",
            "/System/Library/Fonts/HelveticaNeue.ttc",
            "/System/Library/Fonts/SFNS.ttf",
        ]
    else:
        candidates = [
            "/System/Library/Fonts/HelveticaNeue.ttc",
            "/System/Library/Fonts/SFNS.ttf",
        ]
    for c in candidates:
        if os.path.exists(c):
            try:
                return ImageFont.truetype(c, size=size)
            except Exception:
                continue
    return ImageFont.load_default()


