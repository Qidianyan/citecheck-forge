def split_clause_chunks(text: str, max_chars: int = 82) -> list[str]:
    words = text.strip().split()
    if len(text.strip()) <= max_chars or len(words) <= 6:
        return [text.strip()]
    # Split into balanced readable phrases at comma/semicolon/dash or midpoint
    out = []
    cur = []
    cur_len = 0
    for w in words:
        add = len(w) + (1 if cur else 0)
        punct_break = cur and cur[-1].endswith((",", ";", ":", "—")) and cur_len >= 32
        if cur and (cur_len + add > max_chars or punct_break):
            out.append(" ".join(cur))
            cur = [w]
            cur_len = len(w)
        else:
            cur.append(w)
            cur_len += add
    if cur:
        out.append(" ".join(cur))
    return out


def build_ass_stable(scene_records: list[dict], lead_in: float, out_ass: Path) -> None:
    """Build millisecond-synced ASS subtitles from SentenceBoundary events with exact quantized `seg_dur`."""
    header = """[Script Info]
Title: CiteCheck Codegeist 2026 S+ Demo
ScriptType: v4.00+
PlayResX: 1920
PlayResY: 1080
WrapStyle: 0
ScaledBorderAndShadow: yes

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: GazetteSub,Helvetica Neue,28,&H00E6F0F5,&H00E6F0F5,&H141A1D1F,&H141A1D1F,-1,0,0,0,100,100,0.2,0,3,13,0,2,110,110,16,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
    lines = [header.strip()]
    cursor = 0.0

    for rec in scene_records:
        scene_start = cursor
        tempo = rec.get("tempo", 1.0)
        eff_audio_dur = rec.get("eff_audio_dur", rec["audio_dur"] / tempo)
        raw_sents = rec.get("sentences") or [
            {"text": rec["narration"], "offset_s": 0.0, "duration_s": rec["audio_dur"]}
        ]
        sents = [
            {"text": s["text"], "offset_s": s["offset_s"] / tempo, "duration_s": s["duration_s"] / tempo}
            for s in raw_sents
        ]
        sub_events = []
        for si, s in enumerate(sents):
            st0 = s["offset_s"]
            dur0 = max(0.25, s["duration_s"])
            if si + 1 < len(sents):
                end_cap = max(st0 + dur0, sents[si + 1]["offset_s"] - 0.04)
            else:
                end_cap = min(eff_audio_dur + 0.25, st0 + dur0 + 0.25)
            chunks = split_clause_chunks(s["text"], max_chars=82)
            total_chars = max(1, sum(len(c) for c in chunks))
            t_cur = st0
            span = max(0.3, end_cap - st0)
            for ci, ch in enumerate(chunks):
                frac = len(ch) / total_chars
                t_next = end_cap if ci + 1 == len(chunks) else t_cur + span * frac
                sub_events.append((t_cur, t_next, ch))
                t_cur = t_next

        for t0, t1, txt in sub_events:
            st = scene_start + lead_in + t0
            en = min(scene_start + rec["seg_dur"] - 0.12, scene_start + lead_in + t1)
            if en <= st + 0.15:
                en = min(scene_start + rec["seg_dur"] - 0.08, st + 0.5)
            clean_txt = txt.replace("{", "(").replace("}", ")")
            lines.append(f"Dialogue: 0,{ass_time(st)},{ass_time(en)},GazetteSub,,0,0,0,,{clean_txt}")

        cursor += rec["seg_dur"]

    out_ass.write_text("\n".join(lines) + "\n", encoding="utf-8")


def audit_encoded_mp4(mp4_path: Path) -> dict:
    probe_json = json.loads(
        subprocess.check_output(
            ["ffprobe", "-v", "error", "-show_format", "-show_streams", "-of", "json", str(mp4_path)],
            text=True,
        )
    )
    v_stream = next(s for s in probe_json["streams"] if s["codec_type"] == "video")
    a_stream = next(s for s in probe_json["streams"] if s["codec_type"] == "audio")
    dur = float(probe_json["format"]["duration"])

    assert v_stream["codec_name"] == "h264", f"Expected h264, got {v_stream['codec_name']}"
    assert int(v_stream["width"]) == 1920 and int(v_stream["height"]) == 1080, "Expected 1920x1080"
    assert a_stream["codec_name"] == "aac", f"Expected aac, got {a_stream['codec_name']}"
    assert 170.0 <= dur <= 220.0, f"Expected duration in 170..220s, got {dur:.2f}s"

    # Sample 10 timestamps across the encoded MP4 (one inside each scene with burnt-in subtitles visible)
    max_band_sat = 0.0
    with tempfile.TemporaryDirectory(prefix="citecheck_audit_") as tmp_str:
        tmp = Path(tmp_str)
        for idx in range(10):
            ts = min(dur - 1.0, (idx + 0.5) * (dur / 10.0))
            frame_png = tmp / f"sample_{idx:02d}.png"
            subprocess.run(
                ["ffmpeg", "-y", "-ss", f"{ts:.2f}", "-i", str(mp4_path), "-frames:v", "1", str(frame_png)],
                check=True,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.PIPE,
            )
            stats = assert_zero_blue_purple_pil(Image.open(frame_png), f"MP4@{ts:.1f}s")
            max_band_sat = max(max_band_sat, stats["max_sat_175_320"])

    return {
        "video_codec": v_stream["codec_name"],
        "audio_codec": a_stream["codec_name"],
        "width": int(v_stream["width"]),
        "height": int(v_stream["height"]),
        "fps": v_stream.get("r_frame_rate"),
        "duration_s": round(dur, 2),
        "size_mb": round(mp4_path.stat().st_size / (1024 * 1024), 2),
        "hsv_175_320_forbidden_pixels": 0,
        "max_sat_175_320": round(max_band_sat, 4),
    }


