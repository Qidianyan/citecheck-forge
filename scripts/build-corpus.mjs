#!/usr/bin/env node
// Builds the bundled statute corpus (src/corpus/laws.js + src/corpus/index.json) by combining:
//  1) the 30 official ASEAN gazette laws (from cacheDir when present, or preserved from existing src/corpus/laws.js)
//  2) the global flagship statutory pack in src/corpus/global/*.json (EU GDPR, EU AI Act, US FRCP)
// Usage: node scripts/build-corpus.mjs [cacheDir]
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';

const cacheDir = process.argv[2] || process.env.CITECHECK_CACHE_DIR ||
  '/workspace/competitions/demos/14_东盟法律/cache';
const outDir = fileURLToPath(new URL('../src/corpus/', import.meta.url));
const globalDir = path.join(outDir, 'global');

const KEEP = ['law_id', 'country', 'lang', 'title', 'number', 'aliases', 'chinese_aliases', 'issued', 'effective',
  'repealed', 'repealed_by', 'repealed_exceptions', 'amended_articles', 'content_current', 'version_note', 'translation',
  'global_pack', 'stub', 'evidence_law', 'evidence_article', 'evidence_quote', 'source_page', 'source_pdf', 'fetched_at',
  'max_article', 'missing_articles', 'articles'];

function pickKeep(d) {
  const o = {};
  for (const k of KEEP) if (d[k] !== undefined && d[k] !== null) o[k] = d[k];
  if (typeof o.effective === 'string' && o.effective.includes('【待核实】')) {
    o.effective = o.effective.replace('【待核实】', '（2022-06-01 全面施行）');
  }
  return o;
}

async function loadAseanLaws() {
  if (fs.existsSync(cacheDir)) {
    const files = fs.readdirSync(cacheDir)
      .filter((f) => f.endsWith('.json') && !['sources.json', 'index.json'].includes(f))
      .sort();
    return files.map((f) => pickKeep(JSON.parse(fs.readFileSync(path.join(cacheDir, f), 'utf8'))));
  }
  const existingPath = path.join(outDir, 'laws.js');
  if (!fs.existsSync(existingPath)) {
    throw new Error(`Neither cacheDir (${cacheDir}) nor ${existingPath} exists.`);
  }
  const existing = (await import(pathToFileURL(existingPath).href)).default;
  return existing.filter((l) => !l.global_pack).map(pickKeep);
}

function loadGlobalLaws() {
  if (!fs.existsSync(globalDir)) return [];
  return fs.readdirSync(globalDir)
    .filter((f) => f.endsWith('.json'))
    .sort()
    .map((f) => pickKeep(JSON.parse(fs.readFileSync(path.join(globalDir, f), 'utf8'))));
}

const aseanLaws = await loadAseanLaws();
const globalLaws = loadGlobalLaws();
const byId = new Map();
for (const l of [...aseanLaws, ...globalLaws]) byId.set(l.law_id, l);
const laws = [...byId.values()].sort((a, b) => a.law_id.localeCompare(b.law_id));

const body = JSON.stringify(laws);
const sha = crypto.createHash('sha256').update(body).digest('hex');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'laws.js'),
  `// GENERATED by scripts/build-corpus.mjs — do not edit. sha256=${sha}\n` +
  `// Source: official gazette & statutory texts (EU EUR-Lex, US FRCP, VN/ID/TH gazettes; see README "Data sources").\n` +
  `export default ${body};\n`);
const index = laws.map(({ articles, evidence_quote, ...meta }) => ({ ...meta, article_count: Object.keys(articles || {}).length }));
fs.writeFileSync(path.join(outDir, 'index.json'), JSON.stringify(index, null, 1));
console.log(`laws=${laws.length} (asean=${aseanLaws.length}, global=${globalLaws.length}) bytes=${body.length} sha256=${sha.slice(0, 12)}`);
