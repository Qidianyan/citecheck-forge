#!/usr/bin/env node
// Builds the bundled statute corpus (src/corpus/laws.js) from the per-law JSON cache of the
// earlier ASEAN legal-citation project (reused data, see README "Reuse disclosure").
// Usage: node scripts/build-corpus.mjs [cacheDir]
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const cacheDir = process.argv[2] || process.env.CITECHECK_CACHE_DIR ||
  '/workspace/competitions/demos/14_东盟法律/cache';
const outDir = fileURLToPath(new URL('../src/corpus/', import.meta.url));
const KEEP = ['law_id', 'country', 'lang', 'title', 'number', 'aliases', 'chinese_aliases', 'issued', 'effective',
  'repealed', 'repealed_by', 'repealed_exceptions', 'amended_articles', 'content_current', 'version_note', 'translation',
  'stub', 'evidence_law', 'evidence_article', 'evidence_quote', 'source_page', 'source_pdf', 'fetched_at',
  'max_article', 'missing_articles', 'articles'];

const files = fs.readdirSync(cacheDir).filter(f => f.endsWith('.json') && !['sources.json', 'index.json'].includes(f)).sort();
const laws = files.map(f => {
  const d = JSON.parse(fs.readFileSync(path.join(cacheDir, f), 'utf8'));
  const o = {};
  for (const k of KEEP) if (d[k] !== undefined && d[k] !== null) o[k] = d[k];
  return o;
});
const body = JSON.stringify(laws);
const sha = crypto.createHash('sha256').update(body).digest('hex');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'laws.js'),
  `// GENERATED by scripts/build-corpus.mjs — do not edit. sha256=${sha}\n` +
  `// Source: official gazette texts cached 2026-10-15..18 (see README "Data sources").\n` +
  `export default ${body};\n`);
const index = laws.map(({ articles, evidence_quote, ...meta }) => ({ ...meta, article_count: Object.keys(articles || {}).length }));
fs.writeFileSync(path.join(outDir, 'index.json'), JSON.stringify(index, null, 1));
console.log(`laws=${laws.length} bytes=${body.length} sha256=${sha.slice(0, 12)}`);
